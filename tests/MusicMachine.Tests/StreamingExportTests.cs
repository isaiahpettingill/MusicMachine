    [Theory] [InlineData(false)] [InlineData(true)]
    public void CooperativeExportsYieldAndCancelAfterWritingOnASingleThread(bool qoa)
    {
        string directory = NewDirectory();
        SynchronizationContext? previous = SynchronizationContext.Current;
        using var context = new PumpContext();
        try
        {
            SynchronizationContext.SetSynchronizationContext(context);
            string path = Path.Combine(directory, "audio"); File.WriteAllText(path, "keep");
            using var cancellation = new CancellationTokenSource();
            Task export = WriteAsync(path, Tone(), qoa, cancellation.Token);
            Assert.False(export.IsCompleted);
            string temporary = Assert.Single(Directory.GetFiles(directory, "*.tmp"));
            context.RunOne(); // Let at least one actual render/encode/write block finish, then regain control.
            Assert.False(export.IsCompleted);
            Assert.True(new FileInfo(temporary).Length > (qoa ? 8 : 44));
            Assert.Equal("keep", File.ReadAllText(path));
            cancellation.Cancel();
            while (!export.IsCompleted) context.RunOne();
            Assert.ThrowsAny<OperationCanceledException>(() => export.GetAwaiter().GetResult());
            Assert.Equal("keep", File.ReadAllText(path)); Assert.Single(Directory.GetFiles(directory));
        }
        finally { SynchronizationContext.SetSynchronizationContext(previous); Directory.Delete(directory, true); }
    }

