    [Theory] [InlineData("open")] [InlineData("write")] [InlineData("flush")]
    public async Task StorageCommitIgnoresLateUserCancellationAndFinishesAllBytes(string cancelAt)
    {
        string directory = NewDirectory();
        try
        {
            byte[] expected = Enumerable.Range(0, 200000).Select(i => (byte)i).ToArray();
            string source = Path.Combine(directory, "audio"); File.WriteAllBytes(source, expected);
            using var cancellation = new CancellationTokenSource();
            using var file = new FakeStorageFile(); bool finalizing = false;
            file.BeforeOpen = () => { Assert.True(finalizing); if (cancelAt == "open") cancellation.Cancel(); };
            file.Output.BeforeWrite = token =>
            {
                Assert.True(finalizing); Assert.False(token.CanBeCanceled);
                if (cancelAt == "write") cancellation.Cancel();
            };
            file.Output.BeforeFlush = token => { Assert.False(token.CanBeCanceled); if (cancelAt == "flush") cancellation.Cancel(); };
            await Commit(source, file, cancellation.Token, () => finalizing = true);
            Assert.True(cancellation.IsCancellationRequested); Assert.True(finalizing); Assert.Equal(1, file.Opens);
            Assert.True(file.Output.Closed); Assert.Equal(expected, file.Output.ToArray());
        }
        finally { Directory.Delete(directory, true); }
    }

