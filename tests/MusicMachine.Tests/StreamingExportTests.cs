    [Theory] [InlineData(false)] [InlineData(true)]
    public void SongOutputAllocationDoesNotGrowWithAudioDuration(bool qoa)
    {
        // Identical arrangement structure; only tempo changes duration by 20x.
        var pattern = new Pattern { Id = "a", Length = 4 };
        var song = new Song { Bpm = 400, RowsPerBeat = 1, Instruments = [], Tracks = [], Patterns = [pattern], Arrangement = [new() { PatternId = pattern.Id }] };
        string directory = NewDirectory();
        try
        {
            string path = Path.Combine(directory, "audio"); Write(path, song, qoa);
            long before = GC.GetAllocatedBytesForCurrentThread(); Write(path, song, qoa);
            long shortAllocation = GC.GetAllocatedBytesForCurrentThread() - before;
            long shortLength = new FileInfo(path).Length;
            song.Bpm = 20;
            before = GC.GetAllocatedBytesForCurrentThread(); Write(path, song, qoa);
            long longAllocation = GC.GetAllocatedBytesForCurrentThread() - before;
            Assert.True(new FileInfo(path).Length > shortLength * 19);
            Assert.InRange(longAllocation, 0, shortAllocation + 4096);
            Assert.InRange(longAllocation, 0, 128 * 1024);
        }
        finally { Directory.Delete(directory, true); }
    }

    [Fact] public void QoaWriterAllocationIsIndependentOfFrameCount()
    {
        var pcm = new short[5120 * 2];
        void Encode(int frames)
        {
            var writer = new QoaCodec.Writer(Stream.Null, frames * 5120L);
            for (int i = 0; i < frames; i++) writer.WriteFrame(pcm);
            writer.Complete();
        }
        Encode(1);
        long before = GC.GetAllocatedBytesForCurrentThread(); Encode(1);
        long single = GC.GetAllocatedBytesForCurrentThread() - before;
        before = GC.GetAllocatedBytesForCurrentThread(); Encode(64);
        long many = GC.GetAllocatedBytesForCurrentThread() - before;
        Assert.Equal(single, many); Assert.InRange(many, 0, 8192);
    }

    // Called by the existing headless editor regression on its single UI dispatcher.
    internal static void RunControlChecks(MainView view)
    {
        const BindingFlags fields = BindingFlags.Instance | BindingFlags.NonPublic;
        var busy = typeof(MainView).GetField("exportBusy", fields)!;
        var restart = typeof(MainView).GetField("updateRestartApproved", fields)!;
        var status = (TextBlock)typeof(MainView).GetField("status", fields)!.GetValue(view)!;
        object oldBusy = busy.GetValue(view)!, oldRestart = restart.GetValue(view)!;
        string? oldStatus = status.Text; object? oldTip = ToolTip.GetTip(status);
        try
        {
            busy.SetValue(view, true); restart.SetValue(view, false);
            Task<bool> close = view.RequestCloseAsync(); Assert.True(close.IsCompleted); Assert.False(close.GetAwaiter().GetResult());
            Assert.Contains("Finish or cancel", status.Text);
            restart.SetValue(view, true);
            close = view.RequestCloseAsync(); Assert.True(close.IsCompleted); Assert.False(close.GetAwaiter().GetResult());
            var makeProgress = typeof(MainView).GetMethod("ExportProgress", fields)!;
            using var rendering = new CancellationTokenSource();
            object?[] renderArgs = ["WAV", rendering, null];
            var renderDialog = (ContentControl)makeProgress.Invoke(view, renderArgs)!;
            Assert.True(renderDialog.GetLogicalDescendants().OfType<Button>().Single().IsEnabled);
            renderDialog.GetType().GetMethod("Close")!.Invoke(renderDialog, [null]);
            Assert.True(rendering.IsCancellationRequested);
            using var finalizing = new CancellationTokenSource();
            object?[] finalArgs = ["QOA", finalizing, null];
            var finalDialog = (ContentControl)makeProgress.Invoke(view, finalArgs)!;
            ((Action)finalArgs[2]!)();
            var cancel = finalDialog.GetLogicalDescendants().OfType<Button>().Single();
            Assert.False(cancel.IsEnabled);
            Assert.Contains(finalDialog.GetLogicalDescendants().OfType<TextBlock>(), t => t.Text == "Finalizing QOA…");
            cancel.RaiseEvent(new RoutedEventArgs(Button.ClickEvent));
            Assert.False(finalizing.IsCancellationRequested);
