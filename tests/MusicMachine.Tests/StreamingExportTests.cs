    [Fact] public void QoaWriterChecksStreamCancellationCompletenessAndFinalPartialFrame()
    {
        Assert.Throws<ArgumentNullException>(() => new QoaCodec.Writer(null!, 1));
        using var readOnly = new MemoryStream([1, 2], writable: false);
        Assert.Throws<ArgumentException>(() => new QoaCodec.Writer(readOnly, 1));
        using var cancelled = new CancellationTokenSource(); cancelled.Cancel();
        using var stream = new MemoryStream();
        Assert.ThrowsAny<OperationCanceledException>(() => new QoaCodec.Writer(stream, 5121, cancellationToken: cancelled.Token));
        Assert.Equal(0, stream.Length);
        var writer = new QoaCodec.Writer(stream, 5121);
        Assert.Throws<InvalidOperationException>(() => writer.Complete());
        Assert.Throws<ArgumentException>(() => writer.WriteFrame([]));
        Assert.Throws<ArgumentException>(() => writer.WriteFrame(new short[10238]));
        Assert.Throws<ArgumentException>(() => writer.WriteFrame(new short[10241]));
        Assert.Throws<ArgumentException>(() => writer.WriteFrame(new short[10242]));
        Assert.ThrowsAny<OperationCanceledException>(() => writer.WriteFrame(new short[10240], cancelled.Token));
        Assert.Equal(8, stream.Length);
        writer.WriteFrame(new short[10240]);
        long firstLength = stream.Length;
        Assert.Throws<InvalidOperationException>(() => writer.Complete());
        Assert.Throws<ArgumentException>(() => writer.WriteFrame(new short[10240]));
        Assert.Equal(firstLength, stream.Length);
        writer.WriteFrame(new short[2]); writer.Complete(); writer.Complete();
        Assert.Throws<ArgumentException>(() => writer.WriteFrame(new short[2]));
        Assert.ThrowsAny<OperationCanceledException>(() => writer.Complete(cancelled.Token));
        Assert.Equal(QoaCodec.Encode(new short[10242]), stream.ToArray());
        Assert.True(stream.CanWrite); // The caller retains stream ownership.
        using var maximum = new MemoryStream();
        _ = new QoaCodec.Writer(maximum, uint.MaxValue, 0xffffff, 8);
        Assert.Equal(uint.MaxValue, BinaryPrimitives.ReadUInt32BigEndian(maximum.ToArray().AsSpan(4)));
    }

