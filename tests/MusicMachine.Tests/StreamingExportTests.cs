            Assert.False(finalizing.IsCancellationRequested);
            close = view.RequestCloseAsync(); Assert.True(close.IsCompleted); Assert.False(close.GetAwaiter().GetResult());
            busy.SetValue(view, false);
            close = view.RequestCloseAsync(); Assert.True(close.IsCompleted); Assert.True(close.GetAwaiter().GetResult());
        }
        finally { busy.SetValue(view, oldBusy); restart.SetValue(view, oldRestart); status.Text = oldStatus; ToolTip.SetTip(status, oldTip); }
    }

    private static void Write(string path, Song song, bool qoa, CancellationToken token = default, bool includeTail = false)
    { if (qoa) OfflineExporter.WriteQoa(path, song, token, includeTail); else OfflineExporter.WriteWav(path, song, token, includeTail); }
    private static Task WriteAsync(string path, Song song, bool qoa, CancellationToken token = default, bool includeTail = false)
        => qoa ? OfflineExporter.WriteQoaAsync(path, song, token, includeTail) : OfflineExporter.WriteWavAsync(path, song, token, includeTail);
    private static string NewDirectory() => Directory.CreateDirectory(Path.Combine(Path.GetTempPath(), "musicmachine-stream-" + Guid.NewGuid().ToString("N"))).FullName;
    private static Song Tone()
    {
        var song = DemoSong.CreateEmpty(); song.Bpm = 137; song.Patterns[0].Length = 3;
        var part = song.Patterns[0].GetTrack(song.Tracks[0].Id); part.Rows[0] = new() { Kind = NoteKind.Note, Pitch = 69, Effects = ["A37", "V80"] };
        song.Instruments[0].Waveform = Waveform.Noise;
        return song;
    }
    private static short[] Noise(int frames, int channels)
    {
        var pcm = new short[frames * channels]; uint state = 123456;
        for (int i = 0; i < pcm.Length; i++) { state = unchecked(state * 1664525 + 1013904223); pcm[i] = unchecked((short)(state >> 16)); }
        return pcm;
    }
    private static byte[] StreamQoa(short[] pcm, int sampleRate, int channels)
    {
        using var stream = new MemoryStream();
        var writer = new QoaCodec.Writer(stream, pcm.Length / channels, sampleRate, channels);
        for (int offset = 0; offset < pcm.Length; offset += 5120 * channels)
            writer.WriteFrame(pcm.AsSpan(offset, Math.Min(5120 * channels, pcm.Length - offset)));
        writer.Complete(); return stream.ToArray();
    }
    private static byte[] OldWav(float[] stereo, int sampleRate = 48000)
    {
        // Independent frozen layout of the previous BinaryWriter/span export.
        using var stream = new MemoryStream(); using var writer = new BinaryWriter(stream, Encoding.ASCII, leaveOpen: true);
        uint dataSize = checked((uint)stereo.Length * 2);
        writer.Write("RIFF"u8); writer.Write(36u + dataSize); writer.Write("WAVEfmt "u8);
        writer.Write(16u); writer.Write((ushort)1); writer.Write((ushort)2); writer.Write(sampleRate);
        writer.Write(sampleRate * 4); writer.Write((ushort)4); writer.Write((ushort)16); writer.Write("data"u8); writer.Write(dataSize);
        foreach (float value in stereo) writer.Write(OfflineExporter.ToPcm16(value));
        writer.Flush(); return stream.ToArray();
    }
    private static Task Commit(string path, FakeStorageFile file, CancellationToken token, Action finalizing)
        => typeof(MainView).GetMethod("CommitExportAsync", BindingFlags.Static | BindingFlags.NonPublic)!
            .CreateDelegate<Func<string, Func<Task<Stream>>, CancellationToken, Action, Task>>()(path, file.OpenWriteAsync, token, finalizing);
    private sealed class FakeStorageFile : IDisposable
    {
        public readonly ProviderStream Output = new();
        public Action? BeforeOpen;
        public int Opens;
        public Task<Stream> OpenWriteAsync()
        {
            Opens++; BeforeOpen?.Invoke(); Output.SetLength(0);
            return Task.FromResult<Stream>(Output);
        }
        public void Dispose() => Output.Dispose();
    }
    private sealed class ProviderStream : MemoryStream
    {
        public Action<CancellationToken>? BeforeWrite, BeforeFlush;
        public bool FailWrite, FailClose, Closed;
        public ProviderStream() { Write("keep"u8); Position = 0; }
        public override ValueTask WriteAsync(ReadOnlyMemory<byte> buffer, CancellationToken cancellationToken = default)
        {
            BeforeWrite?.Invoke(cancellationToken);
            if (FailWrite) { Write(buffer.Span[..Math.Min(7, buffer.Length)]); throw new IOException("provider write failed"); }
            return base.WriteAsync(buffer, cancellationToken);
        }
        public override Task FlushAsync(CancellationToken cancellationToken)
        { BeforeFlush?.Invoke(cancellationToken); return base.FlushAsync(cancellationToken); }
        public override ValueTask DisposeAsync()
        { Closed = true; base.Dispose(); if (FailClose) throw new IOException("provider close failed"); return ValueTask.CompletedTask; }
    }
    private sealed class PumpContext : SynchronizationContext, IDisposable
    {
        private readonly ConcurrentQueue<(SendOrPostCallback Callback, object? State)> work = new();
        private readonly AutoResetEvent ready = new(false);
        public override void Post(SendOrPostCallback d, object? state) { work.Enqueue((d, state)); ready.Set(); }
        public void RunOne()
        {
            (SendOrPostCallback Callback, object? State) next;
            // A queued callback can be consumed before its AutoResetEvent signal; skip stale signals.
            while (!work.TryDequeue(out next))
                Assert.True(ready.WaitOne(TimeSpan.FromSeconds(10)), "The cooperative exporter did not post a continuation.");
            next.Callback(next.State);
        }
        public void Dispose() => ready.Dispose();
    }
